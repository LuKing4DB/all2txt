"""
关键词相关提示词模板与格式化函数。
"""

# 公共过滤规则（用于第二轮和第三轮检索）
COMMON_FILTERING_RULES = """
【公共过滤规则】（适用于所有关键词处理）：
1. **语法功能词过滤**：过滤所有语法功能词（如助词、连词、介词、语气词等），这些词本身无实际语义，不应作为检索关键词
2. **疑问词过滤**：如果查询是问句，需要判断疑问词是否会在文档中出现
   - 文档通常采用陈述句，大多数疑问词（如"多少"、"什么"、"如何"、"怎样"、"哪里"、"哪个"、"哪些"、"吗"、"呢"）在文档中不会出现，应过滤
   - 例外：如果疑问词可能在文档中出现（如"是否"在"是否符合要求"中），可以保留但权重应较低（0.2-0.3）
3. **干扰词过滤**：对于复合词，判断拆分后的词是否会引入干扰
   - 判断标准：如果某个词是通用词，且与不同前缀/后缀组合会产生不同含义，单独使用会匹配到不相关内容，则应过滤
   - 例如："采购单位"中的"单位"是通用后缀，会匹配"建设单位"、"施工单位"等，应过滤
   - 例如："评标方法"中的"方法"是通用后缀，会匹配"计算方法"、"施工方法"等，应过滤
"""

KEYWORD_EXPANSION_PROMPT = """你是"第三轮检索"的关键词扩展专家。前两轮（原文检索、分词加权）召回不足时才会调用你。

任务：在不过度发散的前提下，为检索提供同义词/相关词/变体词，适度扩展召回。

用户查询: {query}
原始关键词: {keywords}{context_text}

【扩展策略】生成与原始关键词相关的扩展关键词：
1. **同义词扩展**：识别核心概念的同义词，考虑领域内常用表达方式
2. **相关术语扩展**：基于核心概念，生成相关的专业术语和短语组合
3. **表达变体扩展**：识别同一概念的不同表达方式（如正式表达、口语表达、书面语等）
4. **上下文相关扩展**：基于查询上下文，生成可能出现在相关文档中的术语

{common_filtering_rules}

【扩展边界】：
- 扩展的关键词应与原始查询的核心概念高度相关
- 避免过度发散，不要扩展到不相关的领域或概念
- 优先扩展专业术语和领域内常用表达
- 扩展的关键词长度：2-8个字的短语，适合用于文档检索

【示例说明】：
- 查询"投标保证金" → 可扩展为["投标押金", "保证金", "投标担保"]，但避免单独扩展"单位"、"方法"等通用词
- 查询"评标方法" → 可扩展为["评标办法", "评标标准", "评标规则"]，但避免单独扩展"方法"（会引入干扰）

请返回JSON格式：
{{
    "expanded_keywords": ["关键词1", "关键词2", ...]
}}

要求：
- 扩展关键词数量：3-8个
- 必须保持与原始查询高度相关
- 必须过滤语法功能词、疑问词、干扰词
- 只返回JSON，不要其他内容。/nothink"""

KEYWORD_SEGMENTATION_WEIGHT_PROMPT = """你是"第二轮检索"的关键词分析专家（只做分词+权重，不扩展，不改写）。

用户查询: {query}
当前检索结果质量: {quality_feedback}

请分析查询，进行分词并分配权重：
1. 对查询进行分词，提取核心关键词（不扩展、不同义，仅拆分和权重）
2. 根据通用性原则分配权重：越通用的词权重越低，越具体的词权重越高
3. 完整短语（原始查询）必须保留且权重最高

{common_filtering_rules}

【权重分配原则】：
- 完整短语（原始查询）：权重1.0（最高）
- 专业术语/核心实体（名词、动词等有实际语义的词）：权重0.7-0.9
- 中等通用词：权重0.4-0.6
- 非常通用的词：权重0.1-0.3
- 疑问词（如果保留）：权重0.2-0.3

【示例说明】：
- "价格是多少" → ["价格是多少"(1.0), "价格"(0.9)]，过滤"多少"（疑问词）、"是"（语法功能词）
- "采购单位" → ["采购单位"(1.0), "采购"(0.8)]，过滤"单位"（通用后缀，会引入干扰）
- "是否符合要求" → ["是否符合要求"(1.0), "符合要求"(0.8), "要求"(0.7), "是否"(0.3)]，"是否"可保留因为文档中可能出现

请返回JSON格式：
{{
    "keywords": [
        {{"keyword": "关键词1", "weight": 0.9}},
        {{"keyword": "关键词2", "weight": 0.3}},
        ...
    ]
}}

要求：
- 第一个关键词必须是原始查询（权重1.0）
- 仅返回拆分后的关键词及权重，不做扩展/改写
- 必须过滤语法功能词、不会出现的疑问词、会导致干扰的通用词
- 优先提取核心实体（名词、动词等），给予高权重（0.7-0.9）
- 权重范围：0.1-1.0
- 关键词数量：2-5个（不包括应过滤的词）

只返回JSON，不要其他内容。/nothink"""


def format_keyword_expansion(query: str, keywords: str, context_text: str = "") -> str:
    """格式化关键词扩展提示词"""
    return KEYWORD_EXPANSION_PROMPT.format(
        query=query,
        keywords=keywords,
        context_text=context_text,
        common_filtering_rules=COMMON_FILTERING_RULES,
    )


def format_keyword_segmentation_weight(
    query: str, quality_feedback: str = "检索结果质量不足"
) -> str:
    """格式化分词和权重分配提示词"""
    return KEYWORD_SEGMENTATION_WEIGHT_PROMPT.format(
        query=query,
        quality_feedback=quality_feedback,
        common_filtering_rules=COMMON_FILTERING_RULES,
    )

